alter table public.historial add column if not exists ts              timestamptz not null default now();
alter table public.historial add column if not exists accion          text;
alter table public.historial add column if not exists employee_id     text;
alter table public.historial add column if not exists employee_nombre text;
alter table public.historial add column if not exists campo           text;
alter table public.historial add column if not exists valor_anterior  text;
alter table public.historial add column if not exists valor_nuevo     text;

-- La app no envía "hid": la base de datos debe generarlo sola.
do $$
declare
  v_type text;
  v_has_default boolean;
  v_is_identity boolean;
begin
  select c.data_type, c.column_default is not null, c.is_identity = 'YES'
    into v_type, v_has_default, v_is_identity
    from information_schema.columns c
   where c.table_schema = 'public' and c.table_name = 'historial' and c.column_name = 'hid';

  if v_type is null then
    raise notice 'La columna hid no existe; revisa la clave primaria de historial.';
  elsif v_has_default or v_is_identity then
    raise notice 'hid ya se genera automáticamente (%).', v_type;
  elsif v_type = 'uuid' then
    execute 'alter table public.historial alter column hid set default gen_random_uuid()';
  elsif v_type in ('bigint', 'integer', 'smallint') then
    execute 'alter table public.historial alter column hid add generated by default as identity';
  else
    raise notice 'hid es de tipo % sin valor por defecto: asígnale uno manualmente.', v_type;
  end if;
end $$;

-- employee_id debe ser texto: los ids de empleados son cadenas.
-- (La tabla está vacía, así que el cambio de tipo es seguro.)
alter table public.historial alter column employee_id type text using employee_id::text;

-- Índice para ordenar el historial por fecha.
create index if not exists historial_ts_idx on public.historial (ts desc);

-- Recarga el esquema en la API para que reconozca las columnas nuevas.
notify pgrst, 'reload schema';

